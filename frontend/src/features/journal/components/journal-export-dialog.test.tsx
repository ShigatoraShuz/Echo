import { render, screen, within, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, expect, it, vi } from 'vitest';
import { PDFDocument } from 'pdf-lib';
import { JournalExportDialog } from './journal-export-dialog';
import { getJournalService } from '@/services/journal/journal-service.factory';
import type { JournalService } from '@/services/journal/journal.service';
vi.mock('@/services/journal/journal-service.factory', () => ({ getJournalService: vi.fn() }));
afterEach(() => vi.restoreAllMocks());
it('selects journals across pages and downloads one combined PDF only after export', async () => {
  const doc = await PDFDocument.create(); doc.addPage();
  const bytes = (await doc.save()).slice().buffer;
  const pdf = new Blob([bytes], { type: 'application/pdf' });
  Object.defineProperty(pdf, 'arrayBuffer', { value: async () => bytes });
  const listEntries = vi.fn().mockResolvedValueOnce({ success: true, data: { entries: [{ id: 'one', title: 'First reflection', createdAt: '2026-11-18' }], pagination: { totalPages: 2 } } })
    .mockResolvedValueOnce({ success: true, data: { entries: [{ id: 'two', title: 'Second reflection', createdAt: '2026-11-17' }], pagination: { totalPages: 2 } } });
  const exportEntry = vi.fn().mockResolvedValue({ success: true, data: { pdf, filename: 'journal.pdf' } });
  vi.mocked(getJournalService).mockReturnValue({ listEntries, exportEntry } as unknown as JournalService);
  let downloaded!: Blob;
  vi.spyOn(URL, 'createObjectURL').mockImplementation(blob => { downloaded = blob as Blob; return 'blob:export'; });
  const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {});
  render(<JournalExportDialog onClose={vi.fn()} />);
  const user = userEvent.setup();
  expect(await screen.findByText('First reflection')).toBeVisible();
  expect(screen.getByRole('button', { name: 'Export PDF' })).toBeDisabled();
  await user.click(screen.getByRole('checkbox', { name: /First reflection/ }));
  await user.click(screen.getByRole('button', { name: 'Load more journals' }));
  expect(await screen.findByText('Second reflection')).toBeVisible();
  await user.click(screen.getByRole('checkbox', { name: /Second reflection/ }));
  expect(exportEntry).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Export PDF (2)' }));
  await waitFor(() => expect(click).toHaveBeenCalledOnce());
  expect(exportEntry.mock.calls.map(call => call[0])).toEqual(['one', 'two']);
  const merged = await PDFDocument.load(await new Promise<ArrayBuffer>(resolve => { const reader = new FileReader(); reader.onload = () => resolve(reader.result as ArrayBuffer); reader.readAsArrayBuffer(downloaded); }));
  expect(merged.getPageCount()).toBe(2);
});
it('shows export failures without downloading an incomplete selection', async () => {
  const exportEntry = vi.fn().mockResolvedValue({ success: false, error: { message: 'Export unavailable' } });
  const service = { listEntries: vi.fn().mockResolvedValue({ success: true, data: { entries: [{ id: 'one', title: 'My reflection', createdAt: '2026-11-18' }], pagination: { totalPages: 1 } } }), exportEntry };
  vi.mocked(getJournalService).mockReturnValue(service as unknown as JournalService);
  const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {});
  render(<JournalExportDialog onClose={vi.fn()} />);
  const user = userEvent.setup(); await screen.findByText('My reflection');
  await user.click(screen.getByRole('checkbox'));
  await user.click(screen.getByRole('button', { name: 'Export PDF (1)' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Export unavailable');
  expect(click).not.toHaveBeenCalled();
  expect(within(screen.getByRole('dialog')).getByRole('checkbox')).toBeChecked();
});
