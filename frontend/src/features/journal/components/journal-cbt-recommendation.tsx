import { Sparkles } from "lucide-react";
import type { JournalAnalysisResult } from "@echo/contracts";

type NativeResult = Extract<
  JournalAnalysisResult,
  { schemaVersion: "echo-journal-analysis-v2" | "echo-journal-analysis-v3" }
>;

export function JournalCbtRecommendation({ result, heading = "Suggested next steps" }: { result: NativeResult; heading?: string }) {
  if (result.schemaVersion !== "echo-journal-analysis-v3") return null;
  const recommendation = result.cbtRecommendation;
  const supportRequired = result.supportReviewRequired;
  return (
    <section
      aria-label={heading}
      className="mt-5 overflow-hidden rounded-3xl border border-primary/15 bg-gradient-to-br from-secondary/70 via-background to-secondary/20 p-5 shadow-sm motion-safe:animate-in motion-safe:fade-in motion-safe:slide-in-from-bottom-2"
    >
      <div className="mb-3 flex items-center gap-3">
        <span className="rounded-2xl bg-primary/10 p-2.5 text-primary">
          <Sparkles size={19} aria-hidden="true" />
        </span>
        <div>
          <p className="text-[10px] font-bold uppercase tracking-[.18em] text-primary">A gentle way forward</p>
          <h4 className="font-[family-name:var(--font-echo-display)] text-xl">{heading}</h4>
        </div>
      </div>
      {recommendation?.status === "available" && !supportRequired ? (
        <>
          <RecommendationText text={recommendation.text} />
          <p className="mt-3 text-xs leading-6 text-muted-foreground">
            Generated by Buddy’s CBT model for this reflection. Choose what feels useful; these suggestions are
            optional.
          </p>
        </>
      ) : supportRequired || recommendation?.status === "support_required" ? (
        <p className="text-sm leading-7">
          Personal recommendations are paused for this reflection.{" "}
          <a className="font-semibold text-primary underline" href="/crisis-help">
            Explore support options
          </a>{" "}
          or{" "}
          <a className="font-semibold text-primary underline" href="/professional-support">
            talk to a professional
          </a>
          .
        </p>
      ) : (
        <p className="text-sm leading-7 text-muted-foreground">
          {recommendation
            ? "The CBT recommendation could not be generated. Your other analysis results remain saved."
            : "This saved report does not include a CBT recommendation."}
        </p>
      )}
    </section>
  );
}


function RecommendationText({ text }: { text: string }) {
  const inline = (value: string) => value.split(/(\*\*[^*\n]+\*\*|\*[^*\n]+\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") ? <strong key={i}>{part.slice(2, -2)}</strong> : part.startsWith("*") && part.endsWith("*") ? <em key={i}>{part.slice(1, -1)}</em> : part);
  return <div className="space-y-3 break-words text-sm leading-7">{text.split(/\n\s*\n/).map((block, i) => {
    const lines = block.split("\n");
    return lines.every(line => /^\d+[.)]\s+/.test(line))
      ? <ol key={i} className="list-decimal space-y-3 pl-5">{lines.map((line, j) => <li key={j}>{inline(line.replace(/^\d+[.)]\s+/, ""))}</li>)}</ol>
      : <p key={i} className="whitespace-pre-wrap">{inline(block)}</p>;
  })}</div>;
}
