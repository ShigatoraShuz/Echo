import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const names = ["tab-change1.wav", "tab-change2.wav", "tab-change3.wav", "tab-change4.wav", "pop-upboxsound.wav"];
const payload = JSON.stringify(Object.fromEntries(names.map((name) => [name,
  readFileSync(resolve(root, "frontend/assets/interface-sounds", name)).toString("base64"),
])));
const digest = createHash("sha256").update(payload).digest("hex").slice(0, 12);
const directory = resolve(root, "frontend/public/sounds/interface");
mkdirSync(directory, { recursive: true });
writeFileSync(resolve(directory, `cues-${digest}.json`), payload);
writeFileSync(resolve(root, "frontend/src/services/audio/interface-sound-assets.ts"),
  `// Generated by scripts/build-interface-sounds.mjs.\nexport const INTERFACE_SOUND_BUNDLE = "/sounds/interface/cues-${digest}.json";\n`);
console.log("Built one content-versioned JSON sound bundle (no media download requests).");
